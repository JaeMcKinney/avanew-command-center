-- A person may add files only under their own folder, for a client whose tickets they may work.
create policy "support: add your own" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'support'
    and (storage.foldername(name))[2] = (select auth.uid())::text
    and ((select app.has_perm('support.use')) or (select app.has_perm('support.manage')))
    and app.can_access_client(((storage.foldername(name))[1])::uuid)
  );

-- A file can be read by anyone who can read a message that attaches it, so a
-- file on an internal note stays with Divigner.
create policy "support: read attached files" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'support'
    and exists (
      select 1 from public.support_messages m
      where m.attachments @> jsonb_build_array(jsonb_build_object('path', objects.name))
    )
  );
