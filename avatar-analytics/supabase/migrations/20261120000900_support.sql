create policy support_messages_read on public.support_messages for select to authenticated using (
  ((select app.is_staff()) and (select app.has_perm('support.manage')) and app.can_access_client(client_id))
  or (not is_internal and client_id = (select app.my_client_id()) and (select app.has_perm('support.use')))
);

revoke all on public.support_tickets, public.support_ticket_secrets, public.support_messages from anon, authenticated;
