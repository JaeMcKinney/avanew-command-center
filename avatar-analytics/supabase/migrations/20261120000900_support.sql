-- ── Helpers (not callable from the app) ──────────────────────────────────────

/** Whether a given person (not necessarily the caller) may work a client's tickets, and on which side. */
create function app.support_side(p_user_id uuid, p_client_id uuid) returns text
language sql stable security definer set search_path = '' as $$
  select case
    when p.side = 'client' and p.client_id = p_client_id and exists (
      select 1 from public.role_permissions rp where rp.role_id = p.role_id and rp.permission = 'support.use') then 'client'
    when p.side = 'divigner' and exists (
      select 1 from public.role_permissions rp where rp.role_id = p.role_id and rp.permission = 'support.manage')
      and (r.client_scope = 'all' or exists (
        select 1 from public.staff_client_assignments a where a.user_id = p.id and a.client_id = p_client_id)) then 'divigner'
  end
  from public.profiles p join public.roles r on r.id = p.role_id
  where p.id = p_user_id and p.is_active
$$;

/** Checks a list of attached files: at most five, each one uploaded by this person for this client. */
create function app.support_check_attachments(p_attachments jsonb, p_user_id uuid, p_client_id uuid) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_item jsonb;
  v_clean jsonb := '[]';
begin
  if p_attachments is null or jsonb_typeof(p_attachments) <> 'array' or jsonb_array_length(p_attachments) = 0 then
    return '[]';
  end if;
  if jsonb_array_length(p_attachments) > 5 then
    raise exception 'A message can carry at most five files' using errcode = '22023';
  end if;
  for v_item in select * from jsonb_array_elements(p_attachments) loop
    if coalesce(v_item ->> 'path', '') not like p_client_id::text || '/' || p_user_id::text || '/%'
       or not exists (select 1 from storage.objects o where o.bucket_id = 'support' and o.name = v_item ->> 'path') then
      raise exception 'An attached file could not be found' using errcode = '22023';
    end if;
    v_clean := v_clean || jsonb_build_array(jsonb_build_object(
      'path', v_item ->> 'path',
      'name', left(coalesce(nullif(trim(v_item ->> 'name'), ''), 'file'), 200),
      'size', coalesce((v_item ->> 'size')::bigint, 0)));
  end loop;
  return v_clean;
end $$;

/** Adds one entry to a ticket's thread and keeps the ticket's summary in step. */
create function app.support_add_message(
  p_ticket_id uuid, p_author_id uuid, p_author_side text, p_body text,
  p_internal boolean default false, p_kind text default 'message', p_via text default 'portal',
  p_attachments jsonb default '[]', p_email_message_id text default null
) returns uuid
language plpgsql security definer set search_path = '' as $$
declare
  v_ticket public.support_tickets;
  v_name text;
  v_id uuid;
  v_public boolean := p_kind = 'message' and not p_internal;
begin
  select * into v_ticket from public.support_tickets where id = p_ticket_id for update;
  select coalesce(nullif(trim(p.full_name), ''), p.email) into v_name from public.profiles p where p.id = p_author_id;

  insert into public.support_messages (ticket_id, client_id, author_id, author_side, author_name, kind, body, is_internal, via,
                                       attachments, email_message_id, notified_at, notify_result)
  values (p_ticket_id, v_ticket.client_id, p_author_id, p_author_side, coalesce(v_name, ''), p_kind, trim(p_body), p_internal, p_via,
          coalesce(p_attachments, '[]'), p_email_message_id,
          -- Only replies people wrote for the other side are emailed.
          case when v_public then null else now() end, case when v_public then null else 'not sent' end)
  returning id into v_id;

  if v_public then
    update public.support_tickets set
      message_count = message_count + 1,
      last_message_at = now(),
      last_message_side = p_author_side,
      status = case when p_author_side = 'client' then 'open' else 'waiting' end,
      resolved_at = null,
      first_response_at = case when p_author_side = 'divigner' then coalesce(first_response_at, now()) else first_response_at end,
      updated_at = now()
    where id = p_ticket_id;
  else
    update public.support_tickets set updated_at = now() where id = p_ticket_id;
  end if;
  return v_id;
end $$;

