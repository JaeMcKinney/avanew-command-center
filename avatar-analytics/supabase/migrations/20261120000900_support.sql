/**
 * Hands out replies that have not been emailed yet, with who should get each one.
 * A reply from the client goes to the ticket's assignee, or to everyone who runs
 * the desk for that client when nobody is assigned (plus the Owners when it is
 * urgent). A reply from Divigner goes to the client's people on the ticket.
 */
create function public.support_claim_notifications(p_limit integer default 50)
returns table (message_id uuid, ticket_number bigint, subject text, priority text, body text, author_name text, author_side text,
               client_name text, client_slug text, reply_token text, attachment_count integer, recipients text[])
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
begin
  return query
  with claimed as (
    update public.support_messages m
    set notify_claimed_at = now(), notify_attempts = m.notify_attempts + 1
    where m.id in (
      select x.id from public.support_messages x
      where x.notified_at is null and x.notify_attempts < 3
        and (x.notify_claimed_at is null or x.notify_claimed_at < now() - interval '2 minutes')
      order by x.created_at limit greatest(p_limit, 1) for update skip locked)
    returning m.*
  )
  select c.id, t.number, t.subject, t.priority, c.body, c.author_name, c.author_side, cl.name, cl.slug, s.reply_token,
         jsonb_array_length(c.attachments),
         coalesce((
           select array_agg(distinct lower(p.email))
           from public.profiles p join public.roles r on r.id = p.role_id
           where p.is_active and p.id is distinct from c.author_id and (
             (c.author_side = 'client' and (
                (t.assignee_id is not null and p.id = t.assignee_id and app.support_side(p.id, t.client_id) = 'divigner')
                or ((t.assignee_id is null or app.support_side(t.assignee_id, t.client_id) is null) and app.support_side(p.id, t.client_id) = 'divigner')
                or (t.priority = 'urgent' and p.side = 'divigner' and r.key = 'owner')))
             or (c.author_side = 'divigner' and app.support_side(p.id, t.client_id) = 'client' and (
                p.id = t.opened_by
                or exists (select 1 from public.support_messages o where o.ticket_id = t.id and o.author_id = p.id and o.kind = 'message')
                or not exists (
                  select 1 from public.support_messages o join public.profiles op on op.id = o.author_id
                  where o.ticket_id = t.id and o.author_side = 'client' and o.kind = 'message' and op.is_active)))
           )), '{}')
  from claimed c
  join public.support_tickets t on t.id = c.ticket_id
  join public.clients cl on cl.id = t.client_id
  join public.support_ticket_secrets s on s.ticket_id = t.id
  order by c.created_at;
end $$;

/** Records how emailing a reply went. A failure leaves it to be tried again, up to three times. */
create function public.support_mark_notified(p_message_id uuid, p_done boolean, p_result text) returns void
language sql security definer set search_path = '' as $$
  update public.support_messages
  set notified_at = case when p_done or notify_attempts >= 3 then now() end,
      notify_claimed_at = case when p_done then notify_claimed_at end,
      notify_result = left(p_result, 500)
  where id = p_message_id
$$;

/**
 * Files an email that arrived at the support address. With a ticket reference
 * it becomes a reply on that ticket; without one it opens a new ticket. Mail
 * is accepted only from an address that belongs to someone who could have
 * written the same thing in the app.
 */
create function public.support_ingest_email(
  p_from text, p_reference text, p_subject text, p_body text, p_message_id text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_sender public.profiles;
  v_ticket public.support_tickets;
  v_side text;
  v_number bigint;
  v_token text;
  v_body text := nullif(trim(coalesce(p_body, '')), '');
begin
  if p_message_id is not null and exists (select 1 from public.support_messages m where m.email_message_id = p_message_id) then
    return jsonb_build_object('status', 'duplicate');
  end if;
  select * into v_sender from public.profiles p where p.email = lower(trim(p_from)) and p.is_active limit 1;
  if v_sender.id is null then
    perform app.audit('support.email_rejected', 'email', left(p_from, 200), null, jsonb_build_object('reason', 'unknown_sender'));
    return jsonb_build_object('status', 'rejected', 'reason', 'unknown_sender');
  end if;
  if v_body is null then
    return jsonb_build_object('status', 'rejected', 'reason', 'empty');
  end if;
  v_body := left(v_body, 20000);

  if nullif(trim(coalesce(p_reference, '')), '') is not null then
    if p_reference !~ '^t[0-9]{1,12}-[0-9a-f]{8,64}$' then
      return jsonb_build_object('status', 'rejected', 'reason', 'bad_reference');
    end if;
    v_number := substring(p_reference from '^t([0-9]+)-')::bigint;
    v_token := substring(p_reference from '-([0-9a-f]+)$');
    select t.* into v_ticket from public.support_tickets t join public.support_ticket_secrets s on s.ticket_id = t.id
    where t.number = v_number and s.reply_token = v_token;
    v_side := app.support_side(v_sender.id, v_ticket.client_id);
    if v_ticket.id is null or v_side is null then
      perform app.audit('support.email_rejected', 'email', v_sender.email, v_sender.client_id, jsonb_build_object('reason', 'bad_reference'));
      return jsonb_build_object('status', 'rejected', 'reason', 'bad_reference');
    end if;
    perform app.support_add_message(v_ticket.id, v_sender.id, v_side, v_body, false, 'message', 'email', '[]', p_message_id);
    return jsonb_build_object('status', 'added', 'ticket_number', v_ticket.number);
  end if;

  v_side := app.support_side(v_sender.id, v_sender.client_id);
  if v_side is distinct from 'client' then
    perform app.audit('support.email_rejected', 'email', v_sender.email, v_sender.client_id, jsonb_build_object('reason', 'not_a_client'));
    return jsonb_build_object('status', 'rejected', 'reason', 'not_a_client');
  end if;
  insert into public.support_tickets (client_id, subject, opened_by, opened_by_name, opened_via)
  values (v_sender.client_id, left(coalesce(nullif(trim(p_subject), ''), 'Email to support'), 200), v_sender.id,
