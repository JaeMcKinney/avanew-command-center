-- Support desk. A client opens a ticket in their portal (or by email); Divigner
-- staff answer it on the support desk. The whole thread lives here: every
-- reply, every internal note, every status change.
--
-- Who sees what:
--   Client users  their own company's tickets and the replies on them. Never
--                 an internal note.
--   Divigner      staff who run the desk see the tickets of the clients they
--                 may see, with the internal notes.
--
-- Nobody writes to these tables directly. Every change goes through one of
-- the functions below, which check the caller and keep the ticket's summary
-- columns (status, last reply, counts) in step with the thread.
--
-- Files attached to a message live at  support/<client id>/<user id>/<random id>/<file name>
-- and can be read only by someone who can read a message that attaches them.

insert into public.permissions (key, side, label, description, sort) values
  ('support.use',    'client',   'Use support',
   'Open support tickets and reply to them.', 44),
  ('support.manage', 'divigner', 'Run the support desk',
   'Read and answer client tickets, assign them, set their priority and write internal notes.', 54);

insert into public.role_permissions (role_id, permission)
select r.id, p.key from public.roles r cross join public.permissions p
where (r.key in ('client_admin', 'client_member') and p.key = 'support.use')
   or (r.key in ('admin', 'manager') and p.key = 'support.manage')
on conflict do nothing;

-- ── Tables ───────────────────────────────────────────────────────────────────

create table public.support_tickets (
  id                uuid primary key default gen_random_uuid(),
  number            bigint generated by default as identity (start with 1001) unique,
  client_id         uuid not null references public.clients (id) on delete cascade,
  subject           text not null check (length(trim(subject)) between 1 and 200),
  category          text not null default 'question'
                      check (category in ('avatar_down', 'question', 'change_request', 'billing', 'other')),
  priority          text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  -- open = Divigner needs to answer; waiting = the client needs to answer.
  status            text not null default 'open' check (status in ('open', 'waiting', 'resolved')),
  conversation_id   text references public.conversations (conversation_id) on delete set null,
  opened_by         uuid references auth.users (id) on delete set null,
  opened_by_name    text not null default '',
  opened_via        text not null default 'portal' check (opened_via in ('portal', 'email', 'staff')),
  assignee_id       uuid references auth.users (id) on delete set null,
  assignee_name     text,
  message_count     integer not null default 0,
  last_message_at   timestamptz not null default now(),
  last_message_side text not null default 'client' check (last_message_side in ('client', 'divigner')),
  first_response_at timestamptz,
  resolved_at       timestamptz,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);
create index support_tickets_client_idx on public.support_tickets (client_id, last_message_at desc);
create index support_tickets_status_idx on public.support_tickets (status, last_message_at desc);
create index support_tickets_assignee_idx on public.support_tickets (assignee_id);

-- The secret half of a ticket's reply-by-email address. Server only.
create table public.support_ticket_secrets (
  ticket_id   uuid primary key references public.support_tickets (id) on delete cascade,
  reply_token text not null default encode(extensions.gen_random_bytes(12), 'hex')
);

create table public.support_messages (
  id               uuid primary key default gen_random_uuid(),
  ticket_id        uuid not null references public.support_tickets (id) on delete cascade,
  client_id        uuid not null references public.clients (id) on delete cascade,
  author_id        uuid references auth.users (id) on delete set null,
  author_side      text not null check (author_side in ('client', 'divigner')),
  author_name      text not null default '',
  -- message = something a person wrote; event = a change to the ticket (status, assignee, priority).
  kind             text not null default 'message' check (kind in ('message', 'event')),
  body             text not null check (length(trim(body)) between 1 and 20000),
  is_internal      boolean not null default false,
  via              text not null default 'portal' check (via in ('portal', 'email')),
  attachments      jsonb not null default '[]' check (jsonb_typeof(attachments) = 'array'),
  email_message_id text unique,
  notified_at      timestamptz,
  notify_claimed_at timestamptz,
  notify_attempts  integer not null default 0,
  notify_result    text,
  created_at       timestamptz not null default now()
);
create index support_messages_ticket_idx on public.support_messages (ticket_id, created_at);
create index support_messages_pending_idx on public.support_messages (created_at) where notified_at is null;
create index support_messages_attachments_idx on public.support_messages using gin (attachments jsonb_path_ops);

alter table public.support_tickets        enable row level security;
alter table public.support_ticket_secrets enable row level security;
alter table public.support_messages       enable row level security;

create policy support_tickets_read on public.support_tickets for select to authenticated using (
  ((select app.is_staff()) and (select app.has_perm('support.manage')) and app.can_access_client(client_id))
