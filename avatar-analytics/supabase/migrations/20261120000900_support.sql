/** Opens a ticket with its first message. Clients open their own; staff may open one for a client. */
create function public.support_open_ticket(
  p_client_id uuid, p_subject text, p_body text, p_category text default 'question',
  p_conversation_id text default null, p_attachments jsonb default '[]'
) returns public.support_tickets
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := (select auth.uid());
  v_side text := app.support_side(v_me, p_client_id);
  v_name text;
  v_ticket public.support_tickets;
begin
  if v_side is null then
    raise exception 'You do not have permission to open a ticket here' using errcode = '42501';
  end if;
  if p_conversation_id is not null and not exists (
       select 1 from public.conversations c where c.conversation_id = p_conversation_id and c.client_id = p_client_id) then
    raise exception 'That conversation could not be found' using errcode = '22023';
  end if;
  select coalesce(nullif(trim(p.full_name), ''), p.email) into v_name from public.profiles p where p.id = v_me;

  insert into public.support_tickets (client_id, subject, category, priority, status, conversation_id,
                                      opened_by, opened_by_name, opened_via, last_message_side)
  values (p_client_id, trim(p_subject), p_category,
          case when p_category = 'avatar_down' then 'urgent' else 'normal' end,
          case when v_side = 'client' then 'open' else 'waiting' end,
          p_conversation_id, v_me, coalesce(v_name, ''),
          case when v_side = 'client' then 'portal' else 'staff' end, v_side)
  returning * into v_ticket;

  perform app.support_add_message(v_ticket.id, v_me, v_side, p_body, false, 'message', 'portal',
                                  app.support_check_attachments(p_attachments, v_me, p_client_id));
  perform app.audit('support.ticket_opened', 'ticket', v_ticket.number::text, p_client_id,
                    jsonb_build_object('subject', v_ticket.subject, 'category', v_ticket.category));
  select * into v_ticket from public.support_tickets where id = v_ticket.id;
  return v_ticket;
end $$;

/** Adds a reply. Staff may mark it internal, which keeps it from the client. */
create function public.support_reply(
  p_ticket_id uuid, p_body text, p_internal boolean default false, p_attachments jsonb default '[]'
) returns uuid
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := (select auth.uid());
  v_ticket public.support_tickets;
  v_side text;
begin
  select * into v_ticket from public.support_tickets where id = p_ticket_id;
  v_side := app.support_side(v_me, v_ticket.client_id);
  if v_ticket.id is null or v_side is null then
    raise exception 'You do not have permission to reply to this ticket' using errcode = '42501';
  end if;
  if coalesce(p_internal, false) and v_side <> 'divigner' then
    raise exception 'Only Divigner staff can write internal notes' using errcode = '42501';
  end if;
  return app.support_add_message(p_ticket_id, v_me, v_side, p_body, coalesce(p_internal, false), 'message', 'portal',
                                 app.support_check_attachments(p_attachments, v_me, v_ticket.client_id));
end $$;

/** Resolves or reopens a ticket. Clients may do both on their own tickets; only staff may set it to waiting. */
create function public.support_set_status(p_ticket_id uuid, p_status text) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := (select auth.uid());
  v_ticket public.support_tickets;
  v_side text;
begin
  select * into v_ticket from public.support_tickets where id = p_ticket_id;
  v_side := app.support_side(v_me, v_ticket.client_id);
  if v_ticket.id is null or v_side is null then
    raise exception 'You do not have permission to change this ticket' using errcode = '42501';
  end if;
  if p_status not in ('open', 'waiting', 'resolved') or (p_status = 'waiting' and v_side <> 'divigner') then
    raise exception 'That status cannot be set' using errcode = '22023';
  end if;
  if p_status = v_ticket.status then return; end if;

  update public.support_tickets
  set status = p_status, resolved_at = case when p_status = 'resolved' then now() end, updated_at = now()
  where id = p_ticket_id;
  perform app.support_add_message(p_ticket_id, v_me, v_side,
    case p_status when 'resolved' then 'Marked as resolved' when 'open' then 'Reopened' else 'Set to waiting on the client' end,
    false, 'event');
  perform app.audit('support.status_changed', 'ticket', v_ticket.number::text, v_ticket.client_id, jsonb_build_object('status', p_status));
end $$;

/** Gives a ticket to a member of staff, or to nobody (null). Staff only. */
create function public.support_assign(p_ticket_id uuid, p_assignee_id uuid) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := (select auth.uid());
  v_ticket public.support_tickets;
  v_name text;
begin
  select * into v_ticket from public.support_tickets where id = p_ticket_id;
  if v_ticket.id is null or app.support_side(v_me, v_ticket.client_id) is distinct from 'divigner' then
    raise exception 'You do not have permission to assign this ticket' using errcode = '42501';
  end if;
  if p_assignee_id is not null then
    if app.support_side(p_assignee_id, v_ticket.client_id) is distinct from 'divigner' then
      raise exception 'That person cannot work this client''s tickets' using errcode = '22023';
    end if;
    select coalesce(nullif(trim(p.full_name), ''), p.email) into v_name from public.profiles p where p.id = p_assignee_id;
  end if;
  if p_assignee_id is not distinct from v_ticket.assignee_id then return; end if;

  update public.support_tickets set assignee_id = p_assignee_id, assignee_name = v_name, updated_at = now() where id = p_ticket_id;
  perform app.support_add_message(p_ticket_id, v_me, 'divigner',
    case when p_assignee_id is null then 'Unassigned' else 'Assigned to ' || v_name end, false, 'event');
  perform app.audit('support.assigned', 'ticket', v_ticket.number::text, v_ticket.client_id, jsonb_build_object('assignee', v_name));
end $$;

/** Changes a ticket's priority or category. Staff only. Pass null to leave one as it is. */
create function public.support_update_ticket(p_ticket_id uuid, p_priority text default null, p_category text default null) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := (select auth.uid());
  v_ticket public.support_tickets;
begin
  select * into v_ticket from public.support_tickets where id = p_ticket_id;
  if v_ticket.id is null or app.support_side(v_me, v_ticket.client_id) is distinct from 'divigner' then
    raise exception 'You do not have permission to change this ticket' using errcode = '42501';
  end if;
  if p_priority is not null and p_priority <> v_ticket.priority then
    update public.support_tickets set priority = p_priority, updated_at = now() where id = p_ticket_id;
    perform app.support_add_message(p_ticket_id, v_me, 'divigner', 'Priority set to ' || p_priority, true, 'event');
  end if;
  if p_category is not null and p_category <> v_ticket.category then
    update public.support_tickets set category = p_category, updated_at = now() where id = p_ticket_id;
    perform app.support_add_message(p_ticket_id, v_me, 'divigner', 'Category set to ' || replace(p_category, '_', ' '), true, 'event');
  end if;
end $$;

/** The staff who can be given a client's tickets. */
create function public.support_staff(p_client_id uuid) returns table (id uuid, full_name text, email text)
language sql stable security definer set search_path = '' as $$
  select p.id, p.full_name, p.email
  from public.profiles p
  where p.side = 'divigner' and p.is_active
    and app.support_side((select auth.uid()), p_client_id) = 'divigner'
    and app.support_side(p.id, p_client_id) = 'divigner'
  order by p.full_name, p.email
$$;

